"""D2 / V4 STATS.md (new file; make_stats.py / make_stats_v3.py untouched).
  /workspace/venv-tts/bin/python /workspace/hinglish/gen/make_stats_v4.py [OUT.md]
Reads data/V4/{calls.jsonl, gen_report.json, gen_rounds.json, dropped_call_ids.json, holdout.json},
manifests (train/val/test/heldout/all), qc/qc_stats.jsonl, qc_summary.json, work/plan.json, work/utt/*/*.json,
work/timing.jsonl, and the chosen chunk wavs (end level). Everything is split by length_band.
CER flag = best-of-tries chunk CER > its threshold (synth.build 'cer_reject_kept_best'): per-chunk cer_max for
Trelis/method-1 chunks (V4 ASR from 2026-10-04, NOTES "D2 / V4 audio QC: Trelis ASR"), else 0.35 (stock Whisper, as V3).
V4 Trelis CERs are NOT comparable with V3's stock-Whisper CERs."""
import json
import statistics as st
import sys
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np
import soundfile as sf

H = Path(__import__("os").environ.get("HINGLISH_ROOT", "/workspace/hinglish"))
R = H / "data/V4"
W = R / "work"
BASE_WINDOW = 140.0   # trainer duration_sec for V4; WINDOW below = queue_v4_train.sh DUR auto rule (NOTES "D2 / V4 trainer window rule")
OLD_WINDOW = 100.0
CER_MAX = 0.35
TAIL_DB = -15.0
BANDS = ["standard", "long", "mixed"]

calls = {json.loads(l)["call_id"]: json.loads(l) for l in open(R / "calls.jsonl", encoding="utf-8") if l.strip()}
band = {k: c["length_band"] for k, c in calls.items()}
rep = json.load(open(R / "gen_report.json"))
rounds = json.load(open(R / "gen_rounds.json"))
ho = json.load(open(R / "holdout.json"))
qcs = {q["call_id"]: q for q in (json.loads(l) for l in open(R / "qc/qc_stats.jsonl"))}
qsum = json.load(open(R / "qc/qc_summary.json"))
plan = json.load(open(W / "plan.json"))
tim = [json.loads(l) for l in open(W / "timing.jsonl")] if (W / "timing.jsonl").exists() else []


def man(rel):
    p = R / rel
    return [json.loads(l) for l in open(p)] if p.exists() else []


stem = lambda r: Path(r["path"]).stem
scen = lambda cid: cid.rsplit("_", 1)[0]
M = {k: man(f"{k}/{k}.jsonl") for k in ("train", "val", "test")}
M["heldout_all"] = man("heldout/heldout_all.jsonl")
M["all"] = man("manifest/all.jsonl")
dur = {stem(r): r["duration"] for r in M["all"]}
# same rule as queue_v4_train.sh DUR default: 140, or min(ceil(max train/val call s), 160) if the longest is > 140
import math
TV_MAX = max([r["duration"] for r in M["train"] + M["val"]] or [0.0])
WINDOW = BASE_WINDOW if TV_MAX <= BASE_WINDOW else float(min(math.ceil(TV_MAX), 160))
topup = json.load(open(R / "topup_result.json")) if (R / "topup_result.json").exists() else None
fb = Counter(band.values())

# ---- per chunk: chosen try, CER, tries, end level of the chosen wav ----
ch = []  # (call, band, speaker, cer, n_tries, try, end_db, limits)
for ud in sorted((W / "utt").iterdir()):
    for jf in sorted(ud.glob("t*.json")):
        u = json.loads(jf.read_text(encoding="utf-8"))
        for c in u["chunks"]:
            wav = W / "chunks" / u["call_id"] / f"t{u['turn']:02d}_c{c['chunk']}_try{c['try']}.wav"
            e = None
            if wav.exists():
                a, sr = sf.read(str(wav), dtype="float32")
                if a.ndim > 1:
                    a = a.mean(1)
                w = int(0.01 * sr)
                n = len(a) // w
                if n >= 8:
                    r = np.sqrt((a[: n * w].reshape(n, w) ** 2).mean(1) + 1e-12)
                    e = float(20 * np.log10(r[-4:].max() / np.percentile(r, 95)))
            ch.append(dict(call=u["call_id"], band=band.get(u["call_id"]), spk=u["speaker"], cer=c["cer"],
                           n_tries=c["n_tries"], tr=c["try"], end_db=e, cmax=c.get("cer_max", CER_MAX),
                           scorer=c.get("scorer", "whisper_large_v3"), num_ok=c.get("num_ok")))

o = ["# STATS — V4 (D2)", "",
     "Generated by gen/make_stats_v4.py. Length band per call = calls.jsonl `length_band` (hash-assigned).", "",
     "## Text generation (details: gen_report.json, NOTES 'D2 / V4 text generation')",
     f"- calls accepted {rep['n_accepted']}/{rep['n_target']}, dropped {rep['n_dropped']} (data/V4/dropped_call_ids.json)",
     "- by band accepted/target: " + ", ".join(f"{b} {rep['accepted_by_band'][b]}/{rep['target_by_band'][b]}" for b in BANDS),
     "- rounds: " + "; ".join(f"r{r['round']} {r['submitted']}->{r['passed']}" for r in rounds),
     "  (the three lines above are the first text run, 570 calls; gen_report.json is not rewritten by the top-up)"]
if topup:
    o += [f"- top-up (data/V4/topup_go.sh, data/V4_topup; greeting/sign-off exempt from per-band line caps, 'reference' "
          f"exempt from the nukta check): added {len(topup['added'])}, still missing {len(topup['still_missing'])} {topup['still_missing']}"]
o += [f"- FINAL calls.jsonl: {len(calls)}/{rep['n_target']} calls; by band accepted/target: "
      + ", ".join(f"{b} {fb[b]}/{rep['target_by_band'][b]}" for b in BANDS), ""]

# ---- audio overview ----
D = [dur[k] for k in dur]
o += ["## Audio overview",
      f"- TTS backend f5cs (IndicF5 code-switch), voices as V3 (g1 fleurs_hi_m1559/ritu_hinglish, g2 fleurs_hi_m1559/orato_male, "
      f"g3 orato_female/ritu_hinglish, g4 orato_female/orato_male; customer/agent); F5_LONG_BANDS=long,mixed "
      f"(f5cs_long chunk limits 24 words / 140 Devanagari / 200 spoken for long + mixed calls; standard keeps 20/120/170)",
      f"- stereo calls {len(D)}; total {sum(D) / 60:.1f} min ({sum(D) / 3600:.2f} h); per call {min(D):.1f}-{max(D):.1f} s, "
      f"mean {st.mean(D):.1f} s; agent speech {qsum.get('agent_hours')} h",
      f"- trainer window: longest train/val call {TV_MAX:.1f} s -> queue_v4_train.sh DUR auto = {WINDOW:.0f} s "
      f"(rule: 140, or min(ceil(max), 160) if max > 140)",
      f"- calls > {WINDOW:.0f} s (V4 trainer window duration_sec; such a call gets a 2nd window with its own prefix): "
      f"{sum(d > WINDOW for d in D)} {[k for k in sorted(dur) if dur[k] > WINDOW]}",
      f"- calls > {OLD_WINDOW:.0f} s (old window; assemble.py flag over_100s, informational only for V4): {sum(d > OLD_WINDOW for d in D)}",
      f"- failed/missing inputs at assembly: {qsum.get('failed_missing_inputs')}",
      f"- interruptions realised: {qsum.get('interruptions')} (mode {qsum.get('interrupt_mode')})",
      ""]
o += [f"| band | calls | minutes | s/call mean (min-max) | calls > {WINDOW:.0f} s | calls > 100 s |", "|---|---|---|---|---|---|"]
for b in BANDS:
    d = [dur[k] for k in dur if band.get(k) == b]
    if d:
        o.append(f"| {b} | {len(d)} | {sum(d) / 60:.1f} | {st.mean(d):.1f} ({min(d):.1f}-{max(d):.1f}) | "
                 f"{sum(x > WINDOW for x in d)} | {sum(x > OLD_WINDOW for x in d)} |")
o.append("")

# ---- splits ----
test_sc, val_sc = set(ho["test_scenarios"]), set(ho["val_scenarios"])
o += ["## Splits (manifests written by audio/assemble.py --holdout data/V4/holdout.json)",
      f"| split | manifest | calls | scenarios | minutes | standard / long / mixed calls | calls > {WINDOW:.0f} s |", "|---|---|---|---|---|---|---|"]
for k, rel in (("train", "train/train.jsonl"), ("val", "val/val.jsonl"), ("test", "test/test.jsonl"),
               ("heldout_all (all calls of test scenarios)", "heldout/heldout_all.jsonl"), ("all", "manifest/all.jsonl")):
    m = M[k.split(" ")[0]]
    ids = [stem(r) for r in m]
    bc = Counter(band.get(i) for i in ids)
    o.append(f"| {k} | data/V4/{rel} | {len(m)} | {len({scen(i) for i in ids})} | {sum(r['duration'] for r in m) / 60:.1f} | "
             f"{bc['standard']} / {bc['long']} / {bc['mixed']} | {sum(r['duration'] > WINDOW for r in m)} |")
val_ids = {stem(r) for r in M["val"]}
test_ids = {stem(r) for r in M["test"]}
tr_ids = {stem(r) for r in M["train"]}
o += ["",
      f"- val: {len(val_ids)}/{len(ho['val_calls'])} holdout val_calls; val scenarios with no call: "
      f"{sorted(val_sc - {scen(i) for i in val_ids})}; missing val calls: {sorted(set(ho['val_calls']) - val_ids)}",
      f"- test: {len(test_ids)}/{len(ho['test_calls'])} holdout test_calls; missing: {sorted(set(ho['test_calls']) - test_ids)}",
      f"- leak checks: train∩test-scenarios {len({scen(i) for i in tr_ids} & test_sc)}, train∩val-scenarios "
      f"{len({scen(i) for i in tr_ids} & val_sc)}, val∩test-scenarios {len({scen(i) for i in val_ids} & test_sc)}",
      f"- queue_v4_train.sh: pass VAL_N={len(val_ids)} (user: VAL_N = actual val count). Its precheck also asserts "
      f"val scenarios == holdout val_scenarios: "
      f"{'OK' if {scen(i) for i in val_ids} == val_sc else 'WILL STOP - val scenarios without calls: ' + str(sorted(val_sc - {scen(i) for i in val_ids}))}",
      ""]

# ---- TTS QC per band ----
SCORERS = sorted({c["scorer"] for c in ch})
CER_DESC = {"trelis_m1": "Trelis whisper-hinglish-preview, method-1 CER vs text_roman",
            "whisper_large_v3": "min(Devanagari, folded-Latin) vs Whisper large-v3"}
THR = "/".join(sorted({f"{c['cmax']:g}" for c in ch})) or f"{CER_MAX:g}"
o += [f"## TTS QC per length band (chunk level; best try kept; CER = {'; '.join(CER_DESC.get(s, s) for s in SCORERS)})",
      f"| band | chunks | f5cs_long chunks | lines split | CER-flagged (best > {THR}) | flag rate | mean CER | median CER | chunks re-rendered (>1 try) | chosen try 1/2 | loud end after guard (end level > -15 dB) |",
      "|---|---|---|---|---|---|---|---|---|---|---|"]
pl_band = defaultdict(Counter)
for p in plan:
    b = band.get(p["call_id"])
    pl_band[b]["chunks"] += 1
    pl_band[b]["long"] += p.get("limits") == "f5cs_long"
    pl_band[b]["split"] += p["n_chunks"] > 1 and p["chunk"] == 0
for b in BANDS + ["ALL"]:
    x = [c for c in ch if b == "ALL" or c["band"] == b]
    if not x:
        continue
    cer = [c["cer"] for c in x]
    fl = sum(c["cer"] > c["cmax"] for c in x)
    ends = [c["end_db"] for c in x if c["end_db"] is not None]
    loud = sum(e > TAIL_DB for e in ends)
    pb = Counter() if b != "ALL" else sum(pl_band.values(), Counter())
    if b != "ALL":
        pb = pl_band[b]
    o.append(f"| {b} | {len(x)} | {pb['long']} | {pb['split']} | {fl} | {100 * fl / len(x):.2f}% | {st.mean(cer):.4f} | "
             f"{st.median(cer):.4f} | {sum(c['n_tries'] > 1 for c in x)} | {sum(c['tr'] == 1 for c in x)}/{sum(c['tr'] == 2 for c in x)} | "
             f"{loud}/{len(ends)} = {100 * loud / max(1, len(ends)):.2f}% |")
o += ["", "Lines split = lines rendered as >1 chunk. Standard-band greetings of 20-21 words (template 3, top-up calls) exceed the "
      "standard f5cs limit of 20 words and are split in two; expected, not a defect.", "", "Per speaker (all bands):"]
for s in ("agent", "customer"):
    x = [c for c in ch if c["spk"] == s]
    if x:
        o.append(f"- {s}: chunks {len(x)}, flagged {sum(c['cer'] > c['cmax'] for c in x)} "
                 f"({100 * sum(c['cer'] > c['cmax'] for c in x) / len(x):.2f}%), mean CER {st.mean(c['cer'] for c in x):.4f}")
nb = [c for c in ch if c["num_ok"] is not None]
if nb:
    o.append(f"- number-word sequence mismatch (Trelis, informational, not a reject criterion): "
             f"{sum(c['num_ok'] is False for c in nb)}/{len(nb)} chosen chunks with numbers ("
             + ", ".join(f"{bb} {sum(c['num_ok'] is False for c in nb if c['band'] == bb)}/{sum(c['band'] == bb for c in nb)}" for bb in BANDS) + ")")
o += ["",
      "- TTS stages (chunks per try; try1/2 = re-renders of CER-rejected chunks): "
      + "; ".join(f"{t['stage']} {t['chunks']} chunks, {t.get('s_per_chunk')} s/chunk, wall {t.get('wall_s')} s" for t in tim if t["stage"].startswith("tts")),
      f"- F5 tail guard (pre-guard loud ends re-rendered once with +0.5 s): re-rendered {sum(t.get('tail_rerender', 0) for t in tim)}, "
      f"fixed {sum(t.get('tail_fixed', 0) for t in tim)} (all tries)",
      f"- qc_summary: chunks {qsum['chunks']}, cer_flagged {qsum['cer_flagged_chunks']} "
      f"({100 * qsum['cer_flagged_chunks'] / max(1, qsum['chunks']):.2f}%), mean per-call CER {qsum['mean_cer']}; "
      f"V3 reference (stock Whisper, threshold 0.35, not comparable with Trelis): 4345 chunks, 59 flagged (1.36%), mean 0.0886",
      f"- alignment (MMS_FA): fallback utterances {qsum['align_fallback_utts']}, low-score utterances {qsum['align_low_utts']}",
      ""]

# ---- per-call QC per band ----
o += ["## Per-call QC by band", "| band | calls | calls with >=1 CER flag | mean agent speech s | mean agent words | align fallback utts |", "|---|---|---|---|---|---|"]
for b in BANDS:
    q = [qcs[k] for k in qcs if band.get(k) == b]
    if q:
        o.append(f"| {b} | {len(q)} | {sum(x['cer_flagged'] > 0 for x in q)} | {st.mean(x['agent_speech_s'] for x in q):.1f} | "
                 f"{st.mean(x['n_agent_words'] for x in q):.1f} | {sum(x['align_fallback'] for x in q)} |")
o += ["", "## Hindi share (frozen counter, per call pooled per speaker)"]
for b in BANDS:
    cs = [calls[k] for k in calls if band[k] == b]
    ag = [c["hindi_token_share"]["agent"] for c in cs]
    cu = [c["hindi_token_share"]["customer"] for c in cs]
    o.append(f"- {b}: agent {st.mean(ag):.3f} ± {st.pstdev(ag):.3f}, customer {st.mean(cu):.3f} ± {st.pstdev(cu):.3f}")
o += ["", "## QC artefacts", "- data/V4/qc/: align_*.png (qc.py plots), mimi_*.wav + mimi_*_orig.wav (Mimi round-trips, qc.py mimi), "
      "qc_stats.jsonl, qc_summary.json", ""]
out = Path(sys.argv[1]) if len(sys.argv) > 1 else R / "STATS.md"
out.write_text("\n".join(o) + "\n", encoding="utf-8")
print("\n".join(o))
